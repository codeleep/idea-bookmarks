#!/usr/bin/env python3
"""Build, exercise and package the plugin; bootstrap the pinned SDK on Linux CI."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import platform
import shutil
import subprocess
import sys
import tarfile
import tempfile

from build import ROOT, BUILD_NUMBER, PLUGIN_VERSION, product_info, sdk_contents


def sha256(path):
    digest = hashlib.sha256()
    with path.open("rb") as source:
        for block in iter(lambda: source.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def validate_sdk(sdk, lock):
    info = product_info(sdk)
    if info.get("buildNumber") != BUILD_NUMBER or info.get("version") != lock["version"]:
        raise SystemExit(f"Expected IDEA {lock['version']} / {BUILD_NUMBER}; got {info.get('version')} / {info.get('buildNumber')}")
    return sdk


def prepare_sdk(lock):
    if platform.system() != "Linux" or platform.machine().lower() not in ("x86_64", "amd64"):
        raise SystemExit("Automatic SDK download requires Linux x64; otherwise pass --idea-home")
    cache = ROOT / ".cache"
    cache.mkdir(exist_ok=True)
    destination = cache / "ci-idea"
    marker = destination / ".bookmarks-sdk.sha256"
    if marker.is_file() and marker.read_text().strip() == lock["sha256"]:
        return validate_sdk(destination, lock)
    if destination.exists():
        raise SystemExit(f"Unrecognized SDK directory: {destination}; move it aside before retrying")
    with tempfile.TemporaryDirectory(prefix="idea-sdk-", dir=cache) as temporary:
        staging = Path(temporary)
        archive = staging / "idea.tar.gz"
        print(f"Downloading official IDEA {lock['version']} Linux x64 SDK", flush=True)
        subprocess.run(["curl", "--fail", "--location", "--retry", "2", "--retry-delay", "5",
                        "--connect-timeout", "20", "--max-time", "300", "--output", str(archive), lock["url"]], check=True)
        actual = sha256(archive)
        if actual != lock["sha256"]:
            raise SystemExit(f"Official SDK SHA-256 mismatch: expected {lock['sha256']}, got {actual}")
        unpacked = staging / "unpacked"
        unpacked.mkdir()
        # The official archive has already passed its pinned SHA-256 check.
        with tarfile.open(archive, "r:gz") as package:
            package.extractall(unpacked, filter="data")
        candidates = list(unpacked.glob("*/product-info.json"))
        if len(candidates) != 1:
            raise SystemExit("Official SDK archive must contain exactly one product root")
        sdk = validate_sdk(candidates[0].parent, lock)
        shutil.move(str(sdk), destination)
    marker.write_text(lock["sha256"] + "\n")
    return destination


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--idea-home", type=Path, help="Reuse an installed official SDK instead of downloading Linux x64 SDK")
    args = parser.parse_args()
    lock = json.loads((ROOT / ".github/idea-sdk.json").read_text())
    if lock["build"] != BUILD_NUMBER:
        raise SystemExit("SDK lock build must match plugin/plugin.xml since-build")
    sdk = validate_sdk(sdk_contents(args.idea_home), lock) if args.idea_home else prepare_sdk(lock)
    for script, extra in [
        ("verify_sources.py", []),
        ("build.py", ["--idea-home", str(sdk)]),
        ("runtime_smoke.py", ["--idea-home", str(sdk)]),
        ("package_sources.py", []),
    ]:
        subprocess.run([sys.executable, str(ROOT / "tools" / script), *extra], cwd=ROOT, check=True)

    plugin = ROOT / f"dist/bookmarks-desktop-{PLUGIN_VERSION}.zip"
    sources = ROOT / f"dist/idea-bookmarks-{PLUGIN_VERSION}-sources.zip"
    checksums = ROOT / "dist/SHA256SUMS"
    # Include only the two files generated by this invocation, even in a used workspace.
    checksums.write_text("".join(f"{sha256(path)}  {path.name}\n" for path in (plugin, sources)))
    print(f"CI_BUILD_PASS: {plugin.name}", flush=True)
    output = os.environ.get("GITHUB_OUTPUT")
    if output:
        with Path(output).open("a") as stream:
            for key, value in {"version": PLUGIN_VERSION, "plugin_zip": plugin.relative_to(ROOT).as_posix(),
                               "source_zip": sources.relative_to(ROOT).as_posix()}.items():
                stream.write(f"{key}={value}\n")


if __name__ == "__main__":
    main()
