#!/usr/bin/env python3
"""Install the ZIP into isolated user plugins; run the official IDE unmodified."""
import argparse
from copy import deepcopy
import hashlib
import json
import os
import platform
from pathlib import Path
import shutil
import subprocess
import zipfile
import xml.etree.ElementTree as ET

from build import ROOT, PLUGIN_VERSION, product_info, runtime_home, sdk_contents


def prepare_anchor_fixture(sandbox):
    from bookmarks_store import apply_model, encode_xml, load_source, source_lines, write_state
    project = sandbox / "anchor-project"
    (project / ".idea").mkdir(parents=True)
    source = "class AnchorFixture {\r\n    void spaces() {}\r\n\tvoid tabs() {}\r\n    void trailing() {}  \t\r\n    // 中文注释  \r\n    void optional() {}\r\n}\r\n"
    (project / "AnchorFixture.java").write_bytes(b"\xef\xbb\xbf" + source.encode("utf-8"))
    empty = {"formatVersion": 2, "bookmarks": [], "groups": []}
    root = ET.Element("project", version="4")
    component = write_state(empty, "component"); component.set("name", "BookmarksManager"); root.append(component)
    path = project / ".idea/bookmarks.xml"
    path.write_bytes(encode_xml(root))
    model, _, original = load_source(project)
    for line, suffix in enumerate(("spaces", "tabs", "trailing", "chinese", "optional"), start=1):
        attributes = {"url": "file://$PROJECT_DIR$/AnchorFixture.java", "line": str(line)}
        if suffix != "optional": attributes["lineText"] = source_lines((project / "AnchorFixture.java").read_bytes())[line]
        model["bookmarks"].append({"id": "anchor-"+suffix, "provider": "com.intellij.ide.bookmark.providers.LineBookmarkProvider", "attributes": attributes,
                                   "type": "DEFAULT", "descriptionMarkdown": "精确锚点 · "+suffix})
    ids = [b["id"] for b in model["bookmarks"]]
    model["groups"] = [{"id": "anchor-root", "parentId": None, "name": "精确锚点验收", "isDefault": True, "bookmarkIds": ids.copy()},
                       {"id": "anchor-child", "parentId": "anchor-root", "name": "共享引用", "isDefault": False, "bookmarkIds": ids.copy()}]
    wrong = deepcopy(model)
    for record in wrong["bookmarks"]:
        if "lineText" in record["attributes"]: record["attributes"]["lineText"] = record["attributes"]["lineText"].strip()
    try:
        apply_model(project, wrong)
        raise AssertionError("Trimmed source anchors unexpectedly passed apply")
    except ValueError as error:
        assert "failed (4)" in str(error) and "lineText mismatch" in str(error)
        assert path.read_bytes() == original and not (path.parent / "bookmarks-backups").exists()
        (sandbox / "anchor-rejected.txt").write_text(str(error), encoding="utf-8")
    result = apply_model(project, model)
    assert Path(result["backup"]).read_bytes() == original
    (sandbox / "anchor-tool-result.json").write_text(json.dumps(result, indent=2), encoding="utf-8")


def smoke(sdk, plugin_archive=None, anchors_only=False):
    info = product_info(sdk)
    java_home = runtime_home(sdk)
    archive = plugin_archive.resolve() if plugin_archive else ROOT / f"dist/bookmarks-desktop-{PLUGIN_VERSION}.zip"
    with zipfile.ZipFile(archive) as package:
        from io import BytesIO
        with zipfile.ZipFile(BytesIO(package.read("platform-bookmarks-plugin/lib/platform-bookmarks-plugin.jar"))) as jar:
            version = ET.fromstring(jar.read("META-INF/plugin.xml")).findtext("version")
    sandbox = ROOT / ("build/anchor-smoke" if anchors_only else "build/runtime-sandbox")
    if sandbox.exists():
        shutil.rmtree(sandbox)
    for name in ("config", "system", "log", "plugins", "helper-classes"):
        (sandbox / name).mkdir(parents=True)
    prepare_anchor_fixture(sandbox)
    # Cross-language contract: this file is generated by the same writer AI uses.
    from bookmarks_store import encode_xml, write_state
    fixture = {"formatVersion": 2,
               "bookmarks": [{"id": "ai-stable-bookmark", "provider": "com.intellij.ide.bookmark.providers.LineBookmarkProvider",
                              "attributes": {"url": "file://" + (sandbox / "project/sample.txt").as_posix(), "line": "1", "lineText": "second line"},
                              "type": "LETTER_Z", "descriptionMarkdown": "# AI 原文\n\n**共享** <tag> & 中文\n"}],
               "groups": [{"id": "ai-root", "parentId": None, "name": "AI 根组", "isDefault": False, "bookmarkIds": ["ai-stable-bookmark"]},
                          {"id": "ai-child", "parentId": "ai-root", "name": "AI 子组", "isDefault": True, "bookmarkIds": ["ai-stable-bookmark"]}]}
    (sandbox / "ai-import.xml").write_bytes(encode_xml(write_state(fixture, "ManagerState")))
    (sandbox / "ai-import.json").write_text(json.dumps(fixture, ensure_ascii=False, indent=2), encoding="utf-8")
    with zipfile.ZipFile(archive) as package:
        package.extractall(sandbox / "plugins")
    classpath = [*sorted((sdk / "lib").rglob("*.jar")),
                 sdk / "plugins/markdown/lib/intellij.markdown.jar",
                 *sorted((sandbox / "plugins/platform-bookmarks-plugin/lib").rglob("*.jar"))]
    args = ["-encoding", "UTF-8", "--release", "25", "-proc:none", "-classpath",
            os.pathsep.join(map(str, classpath)), "-d", str(sandbox / "helper-classes"),
            str(ROOT / "tests/runtime/AnchorSmokeStarter.java")]
    if not anchors_only:
        args.extend(str(ROOT / "tests/runtime" / name) for name in ("BookmarkSmokeStarter.java", "BreakpointActionsSmoke.java"))
    arguments = sandbox / "javac.args"
    arguments.write_text("\n".join(json.dumps(value, ensure_ascii=False) for value in args))
    subprocess.run([str(java_home / "bin/javac"), "@" + str(arguments)], check=True)
    helper = sandbox / "plugins/bookmarks-validation/lib"
    helper.mkdir(parents=True)
    with zipfile.ZipFile(helper / "validation.jar", "w", zipfile.ZIP_DEFLATED) as output:
        for path in (sandbox / "helper-classes").rglob("*.class"):
            output.write(path, path.relative_to(sandbox / "helper-classes").as_posix())
        starter = "AnchorSmokeStarter" if anchors_only else "BookmarkSmokeStarter"
        breakpoint_type = '' if anchors_only else '<xdebugger.breakpointType implementation="bookmarks.validation.BreakpointActionsSmoke$LineType"/>'
        output.writestr("META-INF/plugin.xml", f"""<idea-plugin>
  <id>bookmarks.validation</id><name>Bookmarks validation</name><version>1</version><vendor>Local</vendor>
  <depends>com.intellij.modules.platform</depends><depends>intellij.bookmarks.plugin</depends>
  <extensions defaultExtensionNs="com.intellij"><appStarter id="bookmarks-source-smoke" implementation="bookmarks.validation.{starter}"/>{breakpoint_type}</extensions>
</idea-plugin>""")
    system = {"Darwin": "macOS", "Linux": "Linux", "Windows": "Windows"}[platform.system()]
    architectures = {"aarch64", "arm64"} if platform.machine().lower() in {"aarch64", "arm64"} else {"amd64", "x86_64", "x64"}
    launch = next(item for item in info["launch"] if item["os"] == system and item.get("arch", "").lower() in architectures)
    info_root = sdk / "Resources" if (sdk / "Resources/product-info.json").is_file() else sdk
    vm_options = info_root / launch["vmOptionsFilePath"]
    vm = [line.strip() for line in vm_options.read_text().splitlines() if line.strip() and not line.startswith("#")]
    jvm_arguments = [value.replace("$APP_PACKAGE", str(sdk.parent)).replace("$IDE_HOME", str(sdk))
                     for value in launch.get("additionalJvmArguments", [])]
    command = [str(java_home / "bin/java"), *vm, *jvm_arguments,
               "-Didea.home.path=" + str(sdk), "-Djava.awt.headless=true",
               "-Dintellij.platform.load.app.info.from.resources=true", "-Didea.is.internal=true",
               "-Dconsent.confirmation.enabled=false", "-Didea.initially.ask.config=false",
               "-Didea.config.path=" + str(sandbox / "config"), "-Didea.system.path=" + str(sandbox / "system"),
               "-Didea.log.path=" + str(sandbox / "log"), "-Didea.plugins.path=" + str(sandbox / "plugins"),
               "-Dbookmarks.validation.root=" + str(sandbox), "-Dbookmarks.validation.version=" + version, "-cp",
               os.pathsep.join(str(sdk / "lib" / name) for name in launch["bootClassPathJarNames"]),
               launch.get("mainClass", "com.intellij.idea.Main"), "bookmarks-source-smoke"]
    log = sandbox / "process.log"
    print(f"Starting unmodified official IDEA {info['version']}; log: {log}", flush=True)
    with log.open("w") as output:
        result = subprocess.run(command, stdout=output, stderr=subprocess.STDOUT, timeout=180)
    if result.returncode or not (sandbox / ("anchor-result.txt" if anchors_only else "result.txt")).is_file():
        print(log.read_text()[-18000:])
        raise SystemExit(result.returncode or 1)
    if anchors_only:
        report = {"result": "PASS", "sdkVersion": info["version"], "sdkBuild": info["buildNumber"], "pluginVersion": version,
                  "archiveSha256": hashlib.sha256(archive.read_bytes()).hexdigest(), "ideInstallationModified": False,
                  "checks": [line[5:] for line in log.read_text().splitlines() if line.startswith("PASS ")]}
        (sandbox / "validation.json").write_text(json.dumps(report, ensure_ascii=False, indent=2)+"\n")
        print(f"ANCHOR_SMOKE_PASS: plugin {version}; {len(report['checks'])} checks")
        return
    from bookmarks_store import load_source, apply_model, read_json, validate, parse_state
    portable = validate(read_json(sandbox / "portable-export.json"))
    if parse_state(write_state(portable, "ManagerState")) != portable:
        raise SystemExit("IDE portable JSON is not lossless through the offline AI serializer")
    if not portable["bookmarks"][0]["attributes"]["url"].startswith("file://$PROJECT_DIR$/"):
        raise SystemExit("IDE portable JSON leaked the original project path")
    contexts = sandbox / "config/tasks/bookmarks_validation.contexts.zip"
    # The fixture branches must have real source revisions for archive validation.
    for arguments in (["init", "-q", "--initial-branch=validation-a"], ["add", "sample.txt"],
                      ["-c", "user.name=Test", "-c", "user.email=test@example.invalid", "-c", "commit.gpgsign=false", "commit", "-qm", "source fixture"],
                      ["branch", "validation-b"]):
        subprocess.run(["git", "-C", str(sandbox / "project"), *arguments], check=True)
    model, _, _ = load_source(sandbox / "project", contexts, "validation-a")
    record = next(record for record in model["bookmarks"] if record["type"] == "DIGIT_7")
    record["descriptionMarkdown"] += "\nAI branch archive update: 中文 & <tag>"
    apply_model(sandbox / "project", model, contexts, "validation-a")
    print("Restarting official IDEA to verify the AI-edited original branch archive", flush=True)
    with log.open("a") as output:
        result = subprocess.run([*command, "verify-ai-archive"], stdout=output, stderr=subprocess.STDOUT, timeout=180)
    if result.returncode or not (sandbox / "second-process-result.txt").is_file():
        print(log.read_text()[-18000:])
        raise SystemExit(result.returncode or 1)
    print((sandbox / "result.txt").read_text())
    passed = [line[5:] for line in log.read_text().splitlines() if line.startswith("PASS ")]
    passed.append("IDE portable JSON accepted losslessly by offline AI schema and XML writer")
    report = {"result": "PASS", "sdkVersion": info["version"], "sdkBuild": info["buildNumber"],
              "pluginVersion": PLUGIN_VERSION, "archiveSha256": hashlib.sha256(archive.read_bytes()).hexdigest(),
              "installation": "isolated user plugins directory", "ideInstallationModified": False,
              "aiArchiveWriteVerifiedAfterRestart": True,
              "checks": passed}
    (ROOT / "build/runtime-validation.json").write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n")
    build_report = ROOT / "build/build-report.json"
    if build_report.exists():
        value = json.loads(build_report.read_text())
        if value.get("sha256") == report["archiveSha256"]:
            value["runtimeValidated"] = True
            build_report.write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--idea-home", required=True, type=Path)
    parser.add_argument("--anchors-only", action="store_true", help="Run anchor compatibility checks against an existing plugin ZIP")
    parser.add_argument("--plugin-archive", type=Path, help="Existing installable ZIP; requires --anchors-only")
    args = parser.parse_args()
    if args.plugin_archive and not args.anchors_only: parser.error("--plugin-archive requires --anchors-only")
    smoke(sdk_contents(args.idea_home), args.plugin_archive, args.anchors_only)
